from sq1 import *
S=solved()
def report(alg,start=S):
  try: st=apply(start,alg)
  except Exception as e: return 'ERR '+str(e)
  out=[]
  for a in range(12):
    for b in range(12):
      s2=twist(st,a,b)
      dt=[(S[0][i][0],s2[0][i][0]) for i in range(12) if s2[0][i]!=S[0][i]]
      db=[(S[1][i][0],s2[1][i][0]) for i in range(12) if s2[1][i]!=S[1][i]]
      out.append((len(dt)+len(db),a,b,sorted(set(dt)),sorted(set(db)),s2[2]))
  return min(out)
