S=solved()
names={}
def report(alg):
  try: st=apply(S,alg)
  except Exception as e: return 'ERR'
  best=None
  for x in range(12):
    for y in range(12):
      s2=twist(st,x,y)
      dt=sorted(set((S[0][i][0],s2[0][i][0]) for i in range(12) if s2[0][i]!=S[0][i]))
      db=sorted(set((S[1][i][0],s2[1][i][0]) for i in range(12) if s2[1][i]!=S[1][i]))
      sc=len(dt)+len(db)
      if best is None or sc<best[0]: best=(sc,(x if x<=6 else x-12,y if y<=6 else y-12),dt,db,'mid' if s2[2] else '',is_cube(s2))
  return best
